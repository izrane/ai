function isArabicMode() {
    try {
        if (typeof currentLang !== 'undefined' && currentLang === 'ar') return true;
        if (typeof localStorage !== 'undefined' &&
            localStorage.getItem('izran-lang') === 'ar') return true;
    } catch (e) {}
    return false;
}

// échappement HTML local (indépendant de la page hôte)
function esc(s) {
    return String(s == null ? '' : s)
        .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;').replace(/'/g, '&#039;');
}

var I18nAR = {
    // Traduction locale synchrone → chaîne arabe
    translate: function (text) { return localTranslate(text).ar; },

    // Traduction locale + statistiques
    translateDetailed: function (text) { return localTranslate(text); },

    // Hybride : local si couverture suffisante, sinon API en ligne (Promise)
    translateBest: function (text) {
        var local = localTranslate(text);
        if (local.coverage >= 0.55 || local.latin < 3) return Promise.resolve(local.ar);
        return translateOnline(text).catch(function () { return local.ar; });
    },

    // API en ligne directe (Promise)
    translateOnline: translateOnline,

    isArabicMode: isArabicMode,

    // Glossaire inline pour les messages du bot (texte pur, pas de HTML) :
    // « Bonjour » → « مرحبا (Bonjour) » ; si rien n'est traduit → texte brut.
    chatGloss: function (frText) {
        if (!isArabicMode()) return String(frText == null ? '' : frText);
        var local = localTranslate(frText);
        if (local.hits === 0) return String(frText == null ? '' : frText);
        var ar = local.ar;
        var fr = String(frText == null ? '' : frText);
        return ar + ' (' + fr + ')';
    },

    // HTML bilingue pour les listes : arabe en principal, français en petit dessous.
    // opts.mode : 'block' (listes favoris/lexique) ou 'inline' (suggestions, OCR)
    // TTS arabe : si tts-ar.js est chargé, un petit bouton haut-parleur est
    // ajouté à la fin de la ligne arabe (lecture au clic, écouteur délégué).
    defHTML: function (frText, mode) {
        var fr = String(frText == null ? '' : frText);
        if (!isArabicMode()) return esc(fr);
        var local = localTranslate(fr);
        if (local.hits === 0) return esc(fr);
        mode = mode || 'block';
        var tag = (mode === 'block') ? 'div' : 'span';
        var tts = '';
        try {
            if (typeof TTSAr !== 'undefined' && TTSAr && typeof TTSAr.btn === 'function') {
                tts = TTSAr.btn(local.ar);
            }
        } catch (e) {}
        var html = '<' + tag + ' class="def-ar"' +
            (local.coverage < 0.55 ? ' data-fr-low="' + esc(fr) + '"' : '') +
            ' dir="rtl" lang="ar">' + esc(local.ar) + tts + '</' + tag + '>' +
            '<' + tag + ' class="def-fr" dir="ltr" lang="fr">' + esc(fr) + '</' + tag + '>';
        return html;
    },

    // Améliore les définitions à faible couverture via l'API (après insertion DOM)
    enhanceDOM: function (root) {
        if (!isArabicMode() || typeof fetch === 'undefined') return;
        var rootEl = root || document;
        var nodes = rootEl.querySelectorAll ? rootEl.querySelectorAll('.def-ar[data-fr-low]') : [];
        Array.prototype.forEach.call(nodes, function (el) {
            var fr = el.getAttribute('data-fr-low');
            translateOnline(fr).then(function (t) {
                if (t) {
                    // TTS arabe : remplacer le texte sans détruire le bouton
                    // haut-parleur, et mettre à jour son attribut data-say.
                    var b = el.querySelector('.tts-ar-btn');
                    if (b) {
                        while (el.firstChild && el.firstChild !== b) el.removeChild(el.firstChild);
                        el.insertBefore(document.createTextNode(t), b);
                        b.setAttribute('data-say', t);
                    } else {
                        el.textContent = t;
                    }
                    el.removeAttribute('data-fr-low');
                }
            }).catch(function () {});
        });
    },

    // Version du module
    version: '1.0.0'
};

global.I18nAR = I18nAR;
if (typeof module !== 'undefined' && module.exports) module.exports = I18nAR; // tests Node

